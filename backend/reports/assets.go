// Package reports собирает PDF и PPTX из снимка отчёта (models.ReportSnapshot).
//
// Оба формата строятся из одной страничной модели (pages.go): блок один раз
// превращается в карточки, график, таблицу и примечания, а рендер каждого
// формата только раскладывает их по макету. Графики рисуются векторно —
// прямоугольниками, линиями и текстом — через общий интерфейс canvas
// (canvas.go), поэтому и PDF, и PPTX получают один и тот же рисунок из одного
// кода, без растров и без библиотеки графиков.
//
// Пакет зависит только от models: формул здесь нет, все числа приходят из
// ответа витрины реестра.
package reports

import (
	_ "embed"
)

// Шрифты встроены в бинарник: образ alpine без шрифтов, а на системные
// рассчитывать нельзя. Inter — свободная лицензия (fonts/LICENSE, OFL),
// полная кириллица, табличные цифры.
var (
	//go:embed fonts/Inter-Regular.ttf
	fontRegular []byte
	//go:embed fonts/Inter-SemiBold.ttf
	fontBold []byte
)

// Пустой шаблон 16:9. Корпоративный подставляется на его место тем же
// именем файла: писатель PPTX ищет в шаблоне макет пустого слайда, а не
// рассчитывает на конкретный номер.
//
//go:embed template/blank.pptx
var pptxTemplate []byte

// fontFamily — имя, под которым шрифт прописывается в PPTX. Файл в
// презентацию не встраивается: PowerPoint подставит Inter, если он есть на
// машине, иначе — шрифт темы. Макет это переживает: текст в PPTX авто-
// подгоняется, а цифры табличные и там, и там.
const fontFamily = "Inter"
