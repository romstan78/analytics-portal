// fontFamily — имя, под которым шрифт прописывается в PPTX. Файл в
// презентацию не встраивается: PowerPoint подставит Inter, если он есть на
// машине, иначе — шрифт темы. Макет это переживает: текст в PPTX авто-
// подгоняется, а цифры табличные и там, и там.
const fontFamily = "Inter"
