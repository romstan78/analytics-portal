// Ключи браузерного хранилища, привязанные к пользователю.
//
// Состояние страницы принадлежит тому, кто его оставил. Без привязки следующий
// вошедший в ту же вкладку открывал экран с чужим выбором: КАМ после админа
// видел фильтр по сети другого КАМа и пустую таблицу под ним — фильтр есть,
// данных нет, и непонятно почему. Разлогин это не лечит: sessionStorage живёт
// до закрытия вкладки, localStorage — и дольше.
//
// Тот же приём уже применён к сохранённым представлениям интернет-продаж и к
// фоновой выгрузке таблицы, поэтому суффикс здесь такой же.

import { getUsername } from '../api/auth';

export function userScopedKey(base: string): string {
  return `${base}:${getUsername() || 'local'}`;
}
